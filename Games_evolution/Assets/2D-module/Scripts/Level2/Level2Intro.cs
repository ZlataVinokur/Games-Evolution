using UnityEngine;
using System.Collections.Generic;

public class Level2Intro : MonoBehaviour
{
    void Start()
    {
        // Останавливаем игру
        Time.timeScale = 0f;

        // Список сообщений
        List<string> introMessages = new List<string>
        {
            "Пиксель, ты вошла в Цифровой Тоннель — место, где старые игровые данные превратились в хаос.",
            "Здесь бродят баги и вирусы. Они мешают нам добраться до Башни Великого Справочника.",
            "Твоя задача: уничтожить 10 вирусов, используя оружие или прыгая на них сверху.",
            "Прыгай по платформам, собирай бонусы и не касайся врагов сбоку — это отнимает здоровье.",
            "Когда уничтожишь всех, уровень завершится автоматически. Удачи, Пиксель!"
        };

        // Показываем последовательные сообщения, после нажатия кнопки "Начать игру" возобновляем игру
        UnifiedInfoSystem.Instance.ShowSequentialMessages(introMessages, () =>
        {
            Time.timeScale = 1f;
        });
    }
}